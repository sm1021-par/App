# 웹앱 화면 구성
st.title("📚 맞춤형 공부 방법 추천 웹앱")

# (1) 공부방법 선택
selected_method = st.selectbox("1. 공부방법 선택", study_methods)

# (2) 과목입력 선택
selected_subject = st.selectbox("2. 과목입력 선택", subjects)

# 분석하기 버튼
if st.button("분석하기"):
  # 함수 호출하여 결과 받아오기
  definition, effects, resources, score, reason = analyze_study_method(
      selected_method, selected_subject
  )

  st.divider()
  st.header(f"🔍 [{selected_method}] 분석 결과")

  # 정의 출력
  st.subheader("1) 정의")
  st.write(definition)

  # 효과 출력 (for 반복문 활용)
  st.subheader("2) 효과")
  for effect in effects:
    st.write(f"- {effect}")

  # 소요자원 테이블표 출력 (for 반복문 활용, 상/중/하 3단계 적용)
  st.subheader("3) 소요자원")
  table_data = []
  for item in resources:
    table_data.append({
        "자원 구분": item[0],
        "소비도 (상/중/하)": item[1],
        "이유": item[2],
    })
  st.table(table_data)

  # 마지막 추천점수, 선정 이유 및 70점 이상 추천 문구 출력
  st.divider()
  st.subheader(f"{selected_subject}의 추천점수:{score}")
  st.write(f"**💡 점수 산출 이유 (과목-방법 상호작용 분석):** {reason}")

  if score >= 70:
    st.success("추천합니다")
  else:
    st.info(
        "단독 활용보다는 다른 공부 방법과 병행하여 보완하는 것을 권장합니다."
    )
